const t = (
  slug: string,
  name: string,
  category: KaliCategory,
  pkg: string,
  invocation: string,
  summary: string,
  homepage?: string,
): KaliTool => {
  const p = P[category];
  return {
    slug,
    name,
    category,
    package: pkg,
    invocation,
    summary,
    homepage: homepage ?? `https://www.kali.org/tools/${pkg}/`,
    depth: "deep",
    commands: [...p.commands(invocation, name), ...help(invocation)],
    errors: p.errors(invocation),
  };
};

